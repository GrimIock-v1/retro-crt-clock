inline const uint8_t* glyph(char c) {
    if (c >= 'a' && c <= 'z') c = char(c - 'a' + 'A');
    const uint8_t u = static_cast<uint8_t>(c);
    if (u >= FIRST && u <= LAST) return GLYPHS[u - FIRST];
    return GLYPHS['?' - FIRST];
}

